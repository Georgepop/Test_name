def travel_ticks(truck, u, v):

    edge_data = G.edges[u, v]

    length = edge_data["length"]
    road_type = edge_data["road_type"]

    road_factor = ROAD_TYPES[road_type]["factor"]

    z_u = G.nodes[u]["z"]
    z_v = G.nodes[v]["z"]

    # Положительный уклон — подъём.
    # Отрицательный уклон — спуск.
    #
    # Горизонтальная длина участка принимается равной
    # длине дороги из входных данных.

    grade = (z_v - z_u) / max(length, 1)

    # Упрощённая модель влияния уклона.
    #
    # Подъём уменьшает скорость.
    # Спуск увеличивает скорость, но не более чем на 10%.

    if grade > 0:
        slope_factor = max(
            0.50,
            1.0 - 3.0 * grade,
        )
    else:
        slope_factor = min(
            1.10,
            1.0 - grade,
        )

    speed_kmh = (
        truck["speed"]
        * road_factor
        * slope_factor
    )

    speed_mps = speed_kmh / 3.6

    travel_seconds = length / speed_mps

    return max(
        1,
        math.ceil(travel_seconds / TIME_STEP),
    )


