def get_candidate_paths(start, target, max_paths=10):

    try:

        paths = nx.shortest_simple_paths(
            G,
            source=start,
            target=target,
            weight="length",
        )

        result = []

        for path in paths:

            result.append(path)

            if len(result) >= max_paths:
                break

        return result

    except (
        nx.NetworkXNoPath,
        nx.NodeNotFound,
    ):
        return []


