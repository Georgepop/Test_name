for truck in TRUCKS:

    truck_id = truck["id"]

    paths = get_full_routes(truck)

    if not paths:

        raise ValueError(
            f"Не удалось построить маршруты для {truck_id}"
        )

    route_vars[truck_id] = []

    completion_terms = []

    for route_idx, route in enumerate(paths):

        path = route["path"]

        selected = model.NewBoolVar(
            f"selected_{truck_id}_{route_idx}"
        )

        route_vars[truck_id].append(selected)

        route_data[(truck_id, route_idx)] = {
            **route,
            "selected": selected,
        }

        current_arrival = model.NewIntVar(
            0,
            HORIZON,
            f"initial_arrival_{truck_id}_{route_idx}",
        )

        model.Add(
            current_arrival == 0
        ).OnlyEnforceIf(selected)

        # ----------------------------------------------------
        # Движение по рёбрам и посещение узлов
        # ----------------------------------------------------

        for edge_idx, (u, v) in enumerate(
            zip(path[:-1], path[1:])
        ):

            duration = travel_ticks(
                truck,
                u,
                v,
            )

            edge_start = model.NewIntVar(
                0,
                HORIZON,
                f"edge_start_{truck_id}_{route_idx}_{edge_idx}",
            )

            edge_end = model.NewIntVar(
                0,
                HORIZON,
                f"edge_end_{truck_id}_{route_idx}_{edge_idx}",
            )

            edge_interval = model.NewOptionalIntervalVar(
                edge_start,
                duration,
                edge_end,
                selected,
                f"edge_interval_{truck_id}_{route_idx}_{edge_idx}",
            )

            model.Add(
                edge_start >= current_arrival
            ).OnlyEnforceIf(selected)

            model.Add(
                edge_end == edge_start + duration
            ).OnlyEnforceIf(selected)

            edge_key = (u, v)

            edge_intervals[edge_key].append({
                "interval": edge_interval,
                "selected": selected,
            })

            arrival = edge_end

            # Обслуживание конечного узла ребра.
            service_ticks = seconds_to_ticks(
                NODE_SERVICE_TIME[v]
            ) if NODE_SERVICE_TIME[v] > 0 else 0

            service_start = model.NewIntVar(
                0,
                HORIZON,
                f"service_start_{truck_id}_{route_idx}_{edge_idx}",
            )

            service_end = model.NewIntVar(
                0,
                HORIZON,
                f"service_end_{truck_id}_{route_idx}_{edge_idx}",
            )

            model.Add(
                service_start >= arrival
            ).OnlyEnforceIf(selected)

            model.Add(
                service_end == service_start + service_ticks
            ).OnlyEnforceIf(selected)

            # Создаём интервал пребывания в узле.
            #
            # Для узлов без обслуживания длительность равна 1 тику,
            # чтобы интервал можно было использовать в CP-SAT.
            node_interval_duration = max(
                1,
                service_ticks,
            )

            node_interval = model.NewOptionalIntervalVar(
                service_start,
                node_interval_duration,
                model.NewIntVar(
                    0,
                    HORIZON + 1,
                    f"node_interval_end_{truck_id}_{route_idx}_{edge_idx}",
                ),
                selected,
                f"node_interval_{truck_id}_{route_idx}_{edge_idx}",
            )

            node_visits[v].append({
                "truck_id": truck_id,
                "route_idx": route_idx,
                "arrival": arrival,
                "service_start": service_start,
                "service_end": service_end,
                "selected": selected,
                "interval": node_interval,
            })

            current_arrival = service_end

        # ----------------------------------------------------
        # Время завершения маршрута
        # ----------------------------------------------------

        completion = model.NewIntVar(
            0,
            HORIZON,
            f"completion_{truck_id}_{route_idx}",
        )

        model.Add(
            completion == current_arrival
        ).OnlyEnforceIf(selected)

        completion_cost = model.NewIntVar(
            0,
            HORIZON,
            f"completion_cost_{truck_id}_{route_idx}",
        )

        model.Add(
            completion_cost == completion
        ).OnlyEnforceIf(selected)

        model.Add(
            completion_cost == 0
        ).OnlyEnforceIf(selected.Not())

        completion_terms.append(completion_cost)

    model.Add(
        sum(route_vars[truck_id]) == 1
    )

    truck_completion[truck_id] = sum(
        completion_terms
    )


