# 10. ФОРМИРОВАНИЕ ПОЛНЫХ МАРШРУТОВ
# ============================================================

def get_full_routes(truck):

    start = truck["start"]

    routes = []

    for loading in LOADING_NODES:

        first_leg = get_candidate_paths(
            start,
            loading,
            NUM_PATHS_PER_LEG,
        )

        if not first_leg:
            continue

        for dump in DUMP_NODES:

            second_leg = get_candidate_paths(
                loading,
                dump,
                NUM_PATHS_PER_LEG,
            )

            for path1 in first_leg:

                for path2 in second_leg:

                    full_path = path1 + path2[1:]

                    # Запрещаем повторные посещения вершин.
                    if len(full_path) != len(set(full_path)):
                        continue

                    # В маршруте обязательно должна быть
                    # погрузка, а последняя вершина — разгрузка.
                    if full_path[-1] != dump:
                        continue

                    if loading not in full_path:
                        continue

                    routes.append({
                        "path": full_path,
                        "loading": loading,
                        "dump": dump,
                    })

    # Удаляем дубликаты.
    unique_routes = []
    seen = set()

    for route in routes:

        key = (
            tuple(route["path"]),
            route["loading"],
            route["dump"],
        )

        if key not in seen:

            seen.add(key)
            unique_routes.append(route)

    return unique_routes


