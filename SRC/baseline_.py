BASELINE_SPEED_KMH = 10.0


def get_shortest_path(G, start, end):
    """
    Кратчайший путь по длине дорог.
    Используются только существующие рёбра графа.
    """
    try:
        return nx.shortest_path(
            G,
            source=start,
            target=end,
            weight="length"
        )
    except (nx.NetworkXNoPath, nx.NodeNotFound):
        return None


def calculate_path_distance(G, path):
    """Длина маршрута в метрах."""
    if not path or len(path) < 2:
        return 0.0

    return sum(
        G[u][v]["length"]
        for u, v in zip(path[:-1], path[1:])
    )


def calculate_baseline_time(distance_m):
    """
    Время движения в секундах при средней скорости 10 км/ч.
    """
    speed_m_s = BASELINE_SPEED_KMH * 1000 / 3600
    return distance_m / speed_m_s


def build_baseline_routes(
    G,
    vehicles,
    start_nodes,
    load_nodes,
    dump_nodes
):
    """
    Для каждой машины:
    1. Определяет стартовую точку.
    2. Выбирает ближайшую по расстоянию точку погрузки.
    3. Выбирает ближайшую по расстоянию точку разгрузки.
    4. Строит маршрут без оптимизации расписания.
    """

    results = []

    for i, vehicle in enumerate(vehicles):
        vehicle_id = vehicle["id"]

        # Распределяем машины между стартовыми точками.
        start = start_nodes[i % len(start_nodes)]

        # Выбираем ближайшую точку погрузки.
        load_candidates = []

        for load in load_nodes:
            path = get_shortest_path(G, start, load)

            if path is not None:
                distance = calculate_path_distance(G, path)
                load_candidates.append((distance, load, path))

        if not load_candidates:
            print(f"{vehicle_id}: нет пути до погрузки")
            continue

        _, load, path_to_load = min(
            load_candidates,
            key=lambda item: item[0]
        )

        # Выбираем ближайшую точку разгрузки от погрузки.
        dump_candidates = []

        for dump in dump_nodes:
            path = get_shortest_path(G, load, dump)

            if path is not None:
                distance = calculate_path_distance(G, path)
                dump_candidates.append((distance, dump, path))

        if not dump_candidates:
            print(f"{vehicle_id}: нет пути до разгрузки")
            continue

        _, dump, path_to_dump = min(
            dump_candidates,
            key=lambda item: item[0]
        )

        # Объединяем участки маршрута.
        full_path = path_to_load + path_to_dump[1:]

        # Расстояние и время.
        distance_m = calculate_path_distance(G, full_path)
        travel_time_sec = calculate_baseline_time(distance_m)

        results.append({
            "id": vehicle_id,
            "start": start,
            "load": load,
            "dump": dump,
            "route": full_path,
            "distance_m": round(distance_m, 2),
            "speed_kmh": BASELINE_SPEED_KMH,
            "travel_time_sec": round(travel_time_sec, 2),
            "travel_time_min": round(travel_time_sec / 60, 2),
        })

    return results


